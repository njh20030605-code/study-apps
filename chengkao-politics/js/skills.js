window.Skills = (function () {
  const TIER_PASS = 0.7;   // 单层(易/中/难)过关线
  const FINAL_PASS = 0.8;  // 最终过关线

  function bank() { return window.QUESTION_BANK.filter(q => q.type==="single" || q.type==="multiple"); }
  function skillQs(sk) { return bank().filter(q => sk.topics.includes(q.topic)); }
  function pools(sk) {
    const qs = skillQs(sk);
    return { easy: qs.filter(q=>q.difficulty===1), mid: qs.filter(q=>q.difficulty===2), hard: qs.filter(q=>q.difficulty===3), all: qs };
  }
  // 这个考点实际有哪几层（有题才算一层）
  function practiceSteps(sk) {
    const p = pools(sk); const out = [];
    if (p.easy.length) out.push({ tier:1, label:"认一认·易", pool:p.easy });
    if (p.mid.length)  out.push({ tier:2, label:"练一练·中", pool:p.mid });
    if (p.hard.length) out.push({ tier:3, label:"挑战·难",  pool:p.hard });
    return out;
  }
  function state(id) {
    const s = Store.get();
    s.skillState = s.skillState || {};
    if (!s.skillState[id]) s.skillState[id] = { conceptRead:false, tiers:[], passed:false };
    return s.skillState[id];
  }
  // 当前该学的考点＝第一个还没过关的
  function currentIndex() {
    for (let i=0;i<SKILLS.length;i++) if (!state(SKILLS[i].id).passed) return i;
    return SKILLS.length-1;
  }
  function currentSkill() { return SKILLS[currentIndex()]; }

  // 这个考点当前处在哪一步：concept / tier / pass / done
  function nextStep(sk) {
    const st = state(sk.id);
    if (!st.conceptRead) return { type:"concept" };
    const ps = practiceSteps(sk);
    const nx = ps.find(s => !st.tiers.includes(s.tier));
    if (nx) return { type:"tier", tier:nx.tier, label:nx.label, pool:nx.pool };
    if (!st.passed) return { type:"pass" };
    return { type:"done" };
  }
  function markConcept(id) { const st=state(id); st.conceptRead=true; Store.save(); }
  function markTier(id, tier) { const st=state(id); if(!st.tiers.includes(tier)) st.tiers.push(tier); Store.save(); }
  function markPassed(id) { const st=state(id); st.passed=true; Store.save(); }

  // 过关测试题：从本考点里挑 ≤6 道（易中难都来点，优先做错过的）
  function passQuiz(sk) {
    const p = pools(sk);
    const pick = [];
    const s = Store.get();
    const wrongFirst = arr => arr.slice().sort((a,b)=>((s.progress[b.id]?.wrong||0)-(s.progress[a.id]?.wrong||0)));
    [p.hard, p.mid, p.easy].forEach(g => wrongFirst(g).slice(0,2).forEach(q=>pick.push(q)));
    // 去重并截断
    const seen={}, out=[];
    pick.forEach(q=>{ if(!seen[q.id]){seen[q.id]=1; out.push(q.id);} });
    return out.slice(0,6);
  }

  function tierPass(acc) { return acc >= TIER_PASS; }
  function finalPass(acc) { return acc >= FINAL_PASS; }

  function overall() {
    const passed = SKILLS.filter(sk=>state(sk.id).passed).length;
    return { passed, total: SKILLS.length };
  }

  return { list:SKILLS, pools, skillQs, practiceSteps, state, currentIndex, currentSkill,
           nextStep, markConcept, markTier, markPassed, passQuiz, tierPass, finalPass, overall,
           TIER_PASS, FINAL_PASS };
})();
